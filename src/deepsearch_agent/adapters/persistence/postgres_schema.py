"""Explicit, checksum-bound business schema migrations; no startup DDL."""
import hashlib
from psycopg import sql


VERSION = 1
DDL = '''
CREATE TABLE access_users (
 id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE, display_name TEXT NOT NULL,
 password_hash TEXT NOT NULL, is_admin INTEGER NOT NULL DEFAULT 0 CHECK(is_admin IN (0,1)),
 disabled INTEGER NOT NULL DEFAULT 0 CHECK(disabled IN (0,1)));
CREATE TABLE access_sessions (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES access_users(id), expires_at DOUBLE PRECISION NOT NULL);
CREATE INDEX access_sessions_user ON access_sessions(user_id);
CREATE INDEX access_sessions_expiry ON access_sessions(expires_at);
CREATE TABLE access_workspaces (id TEXT PRIMARY KEY, name TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL);
CREATE TABLE access_members (
 workspace_id TEXT NOT NULL REFERENCES access_workspaces(id), user_id TEXT NOT NULL REFERENCES access_users(id),
 role TEXT NOT NULL CHECK(role IN ('owner','editor','viewer')), PRIMARY KEY(workspace_id,user_id));
CREATE INDEX access_members_user ON access_members(user_id,workspace_id);
CREATE TABLE access_login_attempts (account_hash TEXT PRIMARY KEY, count INTEGER NOT NULL, expires_at DOUBLE PRECISION NOT NULL);
CREATE INDEX access_login_expiry ON access_login_attempts(expires_at);
CREATE TABLE access_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at DOUBLE PRECISION NOT NULL,
 actor_id TEXT, action TEXT NOT NULL, target_id TEXT, workspace_id TEXT);
CREATE TABLE business_scopes (workspace_id TEXT PRIMARY KEY);
CREATE TABLE sessions (
 workspace_id TEXT NOT NULL REFERENCES business_scopes(workspace_id), id TEXT NOT NULL,
 title TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL, PRIMARY KEY(workspace_id,id));
CREATE INDEX sessions_updated ON sessions(workspace_id,updated_at DESC,id);
CREATE TABLE turns (
 workspace_id TEXT NOT NULL, id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 session_id TEXT NOT NULL, question TEXT NOT NULL, answer_json JSONB NOT NULL, created_at TEXT NOT NULL,
 attachments_json JSONB NOT NULL DEFAULT '[]', run_id TEXT,
 PRIMARY KEY(workspace_id,id), UNIQUE(workspace_id,run_id),
 FOREIGN KEY(workspace_id,session_id) REFERENCES sessions(workspace_id,id) ON DELETE CASCADE);
CREATE INDEX turns_session ON turns(workspace_id,session_id,id);
CREATE TABLE session_memories (
 workspace_id TEXT NOT NULL, session_id TEXT NOT NULL, revision INTEGER NOT NULL, payload JSONB NOT NULL,
 PRIMARY KEY(workspace_id,session_id),
 FOREIGN KEY(workspace_id,session_id) REFERENCES sessions(workspace_id,id) ON DELETE CASCADE);
CREATE TABLE research_runs (
 workspace_id TEXT NOT NULL, id TEXT NOT NULL, session_id TEXT NOT NULL, request_json JSONB NOT NULL,
 status TEXT NOT NULL, stage TEXT NOT NULL, turn_id BIGINT, created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
 PRIMARY KEY(workspace_id,id),
 FOREIGN KEY(workspace_id,session_id) REFERENCES sessions(workspace_id,id) ON DELETE CASCADE,
 FOREIGN KEY(workspace_id,turn_id) REFERENCES turns(workspace_id,id) DEFERRABLE INITIALLY DEFERRED);
CREATE INDEX research_runs_session ON research_runs(workspace_id,session_id,created_at DESC);
'''
SCOPED = ('business_scopes','sessions','turns','session_memories','research_runs')
CHECKSUM = hashlib.sha256((DDL + repr(SCOPED)).encode()).hexdigest()


def validate_schema(database):
    with database.transaction() as db:
        exists = db.execute("SELECT to_regclass('schema_migrations') AS name").fetchone()['name']
        if not exists:
            raise RuntimeError('Business schema absent; run database_cli upgrade before starting the API')
        rows = db.execute('SELECT version,checksum FROM schema_migrations ORDER BY version').fetchall()
        if rows != [{'version':VERSION,'checksum':CHECKSUM}]:
            raise RuntimeError('Business schema version/checksum mismatch; explicit migration required')


def upgrade(database):
    with database.transaction() as db:
        db.execute('SELECT pg_advisory_xact_lock(hashtextextended(%s,0))', ('deepsearch-schema:' + database.settings.schema,))
        db.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {}').format(sql.Identifier(database.settings.schema)))
        db.execute('CREATE TABLE IF NOT EXISTS schema_migrations '
                   '(version INTEGER PRIMARY KEY, checksum TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())')
        existing = db.execute('SELECT version,checksum FROM schema_migrations ORDER BY version').fetchall()
        if existing:
            if existing != [{'version':VERSION,'checksum':CHECKSUM}]:
                raise RuntimeError('Schema version/checksum mismatch; refusing implicit changes')
            return False
        db.execute(DDL)
        for table in SCOPED:
            name = sql.Identifier(table)
            db.execute(sql.SQL('ALTER TABLE {} ENABLE ROW LEVEL SECURITY').format(name))
            db.execute(sql.SQL('ALTER TABLE {} FORCE ROW LEVEL SECURITY').format(name))
            db.execute(sql.SQL("CREATE POLICY workspace_scope ON {} USING "
                "(workspace_id = current_setting('deepsearch.workspace_id',true)) WITH CHECK "
                "(workspace_id = current_setting('deepsearch.workspace_id',true))").format(name))
        db.execute('INSERT INTO schema_migrations(version,checksum) VALUES(%s,%s)', (VERSION,CHECKSUM))
    return True
